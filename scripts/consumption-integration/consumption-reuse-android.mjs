import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {writeFileSync,appendFileSync,copyFileSync} from 'node:fs';
const root=process.env.RUNNER_TEMP;
const source='71e2d11b7146f80b4efdd4f0624b370bbbb04bfe';
const ops='2141580d77901e2e293b3af36fdc5a5b3267b9f2';
assert.equal(process.env.GRIDEX_OPS_COMMIT,ops);
const cwd=process.cwd()+'/gridex-web';
const git=args=>execFileSync('git',args,{cwd,encoding:'utf8',stdio:['ignore','pipe','pipe']}).trim();
execFileSync('git',['fetch','--no-tags','origin',source],{cwd,stdio:['ignore','pipe','pipe']});
const current=git(['rev-parse','HEAD']);
const changed=git(['diff','--name-only',source,current]).split('\n').filter(Boolean);
assert.ok(changed.every(p=>p==='.github/workflows/mobile-consumption-qualification.yml'||p.startsWith('scripts/consumption-integration/')||/^tests\/mobile-consumption-.*\.test\.(mjs|py)$/.test(p)),'Product source changed; Android proof cannot be reused');
const zip=execFileSync('gh',['api',`repos/heke99/gridex-web/actions/artifacts/14046054969/zip`],{maxBuffer:30*1024*1024,stdio:['ignore','pipe','pipe']});
assert.equal(createHash('sha256').update(zip).digest('hex'),'f00671a05295b9d459dab5d7ba1c44b5aba3a96d243a616ed4ba7e632c8c6041');
writeFileSync(root+'/verified-android-source.zip',zip);
execFileSync('unzip',['-q',root+'/verified-android-source.zip','-d',root+'/verified-android-source']);
const original=root+'/verified-android-source';
execFileSync('python3',[cwd+'/scripts/consumption-integration/consumption-native-evidence.py','android',original+'/mobile-android','--ops',ops,'--web',source],{stdio:['ignore','pipe','pipe']});
execFileSync('cp',['-R',original+'/mobile-android',root+'/mobile-android']);
copyFileSync(original+'/consumption-native-observations.json',root+'/consumption-android-reused-observations.json');
const receipt={status:'PASS',originalRun:43437329624,artifactId:14046054969,artifactSHA256:createHash('sha256').update(zip).digest('hex'),opsCommit:ops,originalWebCommit:source,applicableWebCommit:current,changedFiles:changed,productSourceIdentical:true,nativeRerun:false};
writeFileSync(root+'/consumption-android-reuse.json',JSON.stringify(receipt,null,2));
appendFileSync(root+'/mobile-runtime.env',`export GRIDEX_ANDROID_PROOF_COMMIT=${source}\n`);
console.log('Verified original Android evidence; product source identical; no emulator rerun.');
